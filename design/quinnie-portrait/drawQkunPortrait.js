/**
 * 퀴니(Quinnie / 내부 키 qkun) — Q-Learning 세르파 흉상.
 *
 * 플레이어의 첫 동료 세르파. 갈색 강아지 수인 여성(인간형 본체 + 개 귀/꼬리).
 * 동안 + 글래머러스한 볼륨 + 무도가의 단단한 골격. 밝고 단순한 덜렁이 +
 * 우직한 충성심. "어두운 던전 속의 온기"이므로 주변 gloom 보다 한 톤 따뜻하게
 * 읽히되, 고채도 X — RLD 의 절제된 던전 채도 안에서.
 *
 * ── 형제 흉상(drawRepliPortrait / drawRikaPortrait)과 드롭인 호환 ────────────
 * 같은 길드 무대(`_drawGuildScene`)에 나란히 서므로 골격을 동일하게 맞춤:
 *   • (cx, baseY) = 흉상 하단 크롭(허리선) 기준. 몸은 음수 y 로 위로 빌드.
 *     ※ 형제들과 동일: 다리·발 없음(waist-up BUST), torso 바닥 = y 0 = baseY.
 *   • scale = 6 기본 (child/repli/rika 와 동일).
 *   • 표준 골격: torso -19..0(폭 ~12) · neck -21..-19 · head -33..-21(10×12)
 *     · ★ 눈높이 y=-29(형제와 일치) · 코 ~-26 · 입 ~-24 · 머리/귀 -33 위.
 *   • 캐릭터 도트만 그림 — 광원/페이드/딤은 호출부 소유. 광원은 +x 쪽(torch):
 *     +x 모서리 lit, −x 그림자.
 *   • R(x,y,w,h,c) fillRect idiom + 함수 상단 로컬 색 토큰(형제들과 동일 방식;
 *     repli 의 하늘색/금발, rika 의 분홍처럼 캐릭터색은 로컬 토큰으로). raster
 *     이미지·임베드 색은 새로 들이지 않음.
 *
 * ── 톤 가드 ──────────────────────────────────────────────────────────────────
 * 격 = 금빛·고채도가 아니라 태도+온전한 장비. 노골적 성적 강조 X — 볼륨은
 * 모래시계 실루엣 + 절제된 bust 셰이딩으로만. 해상도 대비 과한 디테일 X:
 * 실루엣 먼저(개 귀 + 옆 포니테일 + 한쪽 접힌 귀), 셰이딩은 그 다음.
 *
 * 디자인 신호: 갈색 개 귀(최강 종족 신호) + 꼬리끝 살짝 + 크고 밝은 호박색
 * 눈 + 작은 덧니 미소 + 홍조 = 덜렁이·충성의 따뜻함. 한쪽 귀를 접어 "덜렁이".
 */
export function drawQkunPortrait(ctx, cx, baseY, scale = 6) {
    ctx.save();
    ctx.translate(Math.round(cx), Math.round(baseY));
    ctx.scale(scale, scale);
    const R = (x, y, w, h, c) => { ctx.fillStyle = c; ctx.fillRect(x, y, w, h); };

    // ── 색 토큰 (함수 상단; 형제 흉상과 동일 방식의 로컬 팔레트) ──────────
    const SKIN = '#e6b48e', SKIN_SH = '#c48f6c', SKIN_HI = '#f2e4d4';   // 형제와 동일 피부
    const FUR = '#8a5a34', FUR_SH = '#5f3d22', FUR_HI = '#b07d4a';      // 갈색 개 털/머리
    const EAR_IN = '#d99c86';                                          // 귀 안쪽(분홍빛)
    const GI = '#d8c49a', GI_SH = '#b09a68', GI_HI = '#ece0c4';         // 따뜻한 크림 무도복
    const LEATHER = '#6b4e2e', LEATHER_SH = '#4c3720';                 // 갈색 가죽 가드
    const SASH = '#8b3a1f', SASH_SH = '#5e2613';                       // rust 새시(그녀의 따뜻한 시그니처)
    const EYE = '#c9883f', EYE_D = '#3a2a1c';                          // 호박색 눈 + 어두운 동공
    const BLUSH = '#d9866a', LIP = '#b56a5e';
    const GOLD = '#e6b450';                                            // 브래스 1점(새시 매듭)

    // ════════════════════════════════════════════════════════════════════
    // BUST — 형제와 동일 골격. y 0 = 허리 크롭. 다리/발 없음.
    // ════════════════════════════════════════════════════════════════════

    // ── 꼬리끝 — −x 아래 모서리에서 살짝 위로 말려 frame 으로 비집고 올라옴.
    //    개 수인 신호 보강(허리 아래 본체는 크롭되지만 끝만 보임). ──────────
    R(-9, -6, 3, 5, FUR);                      // 꼬리끝 덩어리
    R(-10, -4, 2, 4, FUR);
    R(-10, -4, 1, 4, FUR_SH);                  // 바깥 그림자
    R(-7, -5, 1, 4, FUR_HI);                   // 안쪽 lit

    // ── TORSO — 무도복 + 모래시계(어깨 넓고 허리 tuck) = 글래머+무도가 ───
    R(-7, -19, 14, 9, GI);                     // 어깨+가슴(넓게)  −19..−10
    R(-6, -10, 12, 10, GI);                    // 허리 tuck        −10..0
    R(-7, -19, 2, 9, GI_SH);                   // 그림자 측(상)
    R(-6, -10, 2, 10, GI_SH);                  // 그림자 측(하)
    R(5, -10, 1, 10, GI_SH);                   // 먼 측 음영
    R(5, -19, 1, 9, GI_HI);                    // +x lit 모서리(상)
    R(5, -10, 1, 6, GI_HI);                    // +x lit 모서리(하)

    // 무도복 V-여밈(겹쳐지는 라펠) + 안쪽 rust 언더랩(노출 없이 따뜻한 V)
    R(-1.5, -19, 3, 3, SASH);                  // 목 아래 안쪽 V(rust)
    R(-1.5, -19, 1.5, 3, SASH_SH);
    R(-5, -19, 4, 2, GI_HI);                   // 왼 라펠(밝은 띠)
    R(1, -19, 4, 2, GI_HI);                    // 오른 라펠
    R(-3.5, -18, 2.5, 5, GI_HI);               // 라펠이 가슴으로 사선
    R(1, -18, 2.5, 5, GI_HI);
    R(-0.6, -17, 1.2, 8, GI_SH);               // 여밈 중심선(그림자)

    // 가슴 볼륨(무도복 톤, 절제 — 둥근 하이라이트 2 + 부드러운 under-curve)
    R(-5, -16, 3, 2, GI_HI); R(2, -16, 3, 2, GI_HI);
    R(-6.3, -15, 1, 3, GI_SH); R(5.3, -15, 1, 3, GI_SH);   // 바깥 측 음영
    R(-6, -12, 4.5, 1, GI_SH); R(1.5, -12, 4.5, 1, GI_SH); // under-curve

    // ── 어깨 가죽 가드(무도가/가드 톤) — +x 어깨에 둥근 폴드런 ──────────
    R(2.5, -20, 5, 4, LEATHER);                // 폴드런 캡
    R(2.5, -20, 5, 1, LEATHER_SH);             // 윗 음영
    R(6.5, -19, 1, 3, FUR_HI);                 // 따뜻한 lit 모서리
    R(3, -16.5, 4, 1, LEATHER_SH);             // 폴드런 밑단
    // 반대쪽(−x) 어깨엔 천을 동여맨 끈만(무도가) — 작은 가죽 스트랩
    R(-7, -17, 2, 1, LEATHER);

    // ── rust 새시 — 허리 크롭 위로 가로지름 + −x 매듭/꼬리, 작은 금빛 매듭쇠 ─
    R(-6, -5, 12, 3, SASH);                    // 새시 밴드
    R(-6, -5, 12, 1, SASH_SH);                 // 윗 음영선
    R(-7, -4, 3, 5, SASH);                     // −x 매듭 + 늘어진 꼬리
    R(-7, -4, 1, 5, SASH_SH);
    R(-1, -5, 2, 2, GOLD);                     // 가운데 작은 매듭쇠(브래스 1점)
    R(-0.5, -5, 1, 1, GI_HI);                  // 글린트

    // ── NECK ────────────────────────────────────────────────────────────
    R(-2, -21, 4, 2, SKIN);
    R(-2, -21, 1.5, 2, SKIN_SH);

    // ── HEAD — 둥글고 큰 동안 (형제 골격 −33..−21, 10×12) ────────────────
    R(-5, -33, 10, 12, SKIN);                  // 얼굴
    R(-5, -33, 2, 12, SKIN_SH);                // 그림자 측(−x)
    R(4, -33, 1, 11, SKIN_HI);                 // lit 모서리(+x)
    R(-4, -22, 8, 1, SKIN_SH);                 // 부드러운 턱 음영

    // ── 갈색 머리 — 이마 프린지 + 옆머리, +x 높은 옆 포니테일(동적 실루엣) ─
    R(-5, -35, 10, 3, FUR);                    // 두상/크라운
    R(-5, -35, 3, 3, FUR_SH);
    R(2, -35, 3, 2, FUR_HI);                   // lit 크라운(+x)
    R(-5, -33, 1.5, 8, FUR);                   // 왼 옆머리(중간 길이)
    R(3.5, -33, 1.5, 7, FUR);                  // 오른 옆머리
    R(-5, -33, 8, 2, FUR);                     // 이마 프린지
    R(-1, -34, 3, 1, FUR_HI);                  // 가르마 하이라이트
    R(-5, -33, 1.5, 5, FUR_SH);                // 왼 옆머리 음영
    // 옆 포니테일(+x, 빛 받음)
    R(5, -34, 3, 4, FUR);                      // 묶음 베이스
    R(6, -31, 3, 7, FUR);                      // 늘어진 꼬리
    R(8, -31, 1, 7, FUR_HI);                   // 바깥 lit
    R(6, -30, 1, 6, FUR_SH);                   // 안쪽 음영
    R(4.5, -33, 2, 1.5, SASH);                 // 머리끈(rust)

    // ── 개 귀 — 머리 위 좌우. 최강 종족 신호. 한쪽 접어 "덜렁이". ─────────
    // 왼 귀(−x, 그림자) — 쫑긋 선 삼각
    R(-7, -37, 3, 3, FUR);
    R(-8, -40, 2.5, 4, FUR);
    R(-8.5, -42, 2, 3, FUR);                   // 끝
    R(-8.5, -42, 1, 5, FUR_SH);                // 바깥 그림자
    R(-6.5, -38, 1, 3, EAR_IN);                // 귀 안쪽(분홍)
    // 오른 귀(+x, 빛) — 끝이 살짝 접힘(덜렁이 포인트)
    R(4, -37, 3, 3, FUR);
    R(5, -40, 2.5, 3, FUR);
    R(5.5, -41, 3, 2, FUR);                    // 접힌 끝(옆으로 꺾임)
    R(7.5, -41, 1, 2, FUR_HI);                 // 접힘 lit 모서리
    R(4.5, -38, 1, 3, EAR_IN);                 // 귀 안쪽

    // ── 얼굴 디테일 — 크고 밝은 호박색 눈 + 작은 코 + 활짝 덧니 미소 + 홍조 ─
    //    눈썹은 따로 두지 않음(형제와 동일) — 프린지가 brow 라인 역할. 부드럽게.
    // 눈 — 크게, 둥글게. 흰자 + 호박 홍채 + 동공 + 큰 캐치라이트(반짝).
    R(-3.6, -29, 2.6, 2, '#f6f1e6');           // 왼 흰자
    R(1, -29, 2.6, 2, '#f6f1e6');              // 오른 흰자
    R(-3.2, -29, 1.8, 2, EYE);                 // 왼 홍채(호박)
    R(1.4, -29, 1.8, 2, EYE);                  // 오른 홍채
    R(-2.6, -28.6, 0.9, 1.3, EYE_D);           // 왼 동공
    R(1.8, -28.6, 0.9, 1.3, EYE_D);            // 오른 동공
    R(-3.0, -29, 1.1, 1, SKIN_HI);             // 왼 캐치라이트(크게 → 반짝)
    R(1.6, -29, 1.1, 1, SKIN_HI);              // 오른 캐치라이트
    R(-1.4, -29, 0.6, 0.6, '#fff');            // 아래 작은 반짝(L)
    R(2.4, -29, 0.6, 0.6, '#fff');             // (R)
    // 작은 코(개 코끝 살짝)
    R(-0.5, -26, 1, 1, FUR_SH);
    // 활짝 웃는 덜렁이 입 — 입꼬리 올라간 열린 미소 + 덧니
    R(-1.8, -24.4, 3.6, 1.4, EYE_D);           // 벌린 입(어둡게)
    R(-2.1, -25, 0.9, 0.9, LIP);               // 왼 입꼬리(살짝 위로)
    R(1.2, -25, 0.9, 0.9, LIP);                // 오른 입꼬리(위로)
    R(-1.2, -23.2, 2.6, 0.7, LIP);             // 아랫입술/혀
    R(-1.4, -24.4, 0.8, 0.8, '#fbf6ea');       // 덧니(fang)
    // 홍조 — 작고 은은하게
    R(-4, -26.2, 1.1, 0.9, BLUSH);
    R(2.9, -26.2, 1.1, 0.9, BLUSH);

    ctx.restore();
}
