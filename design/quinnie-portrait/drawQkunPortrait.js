/**
 * 퀴니(Quinnie / 내부 키 qkun) — Q-Learning 세르파 흉상. (v2)
 *
 * 플레이어의 첫 동료 세르파. 갈색 강아지 수인 여성(인간형 본체 + 개 귀/꼬리).
 * 동안 + 따뜻한 볼륨 + 무도가 기질의 단단함. 밝고 단순한 덜렁이 + 우직한 충성.
 * 백스토리 무드(대사/문서 노출 X, 외형에만 은은히): 과거 주인공의 아버지에게
 * 구출돼 세르파 길드에 들어온 신입 — 길드 잡일/심부름 담당. 그래서 복장은
 * 화려한 무도복이 아니라 **수수한 초보 모험가 차림**(여행자 튜닉 + 조끼 + 심부름
 * 파우치). 아버지를 닮은 마스터를 향한 우직한 충성이 따뜻한 인상으로 묻어남.
 *
 * ── 형제 흉상(drawRepliPortrait / drawRikaPortrait)과 드롭인 호환 ────────────
 *   • (cx, baseY) = 흉상 하단 크롭(허리선) 기준. waist-up BUST(다리/발 없음),
 *     torso 바닥 = y 0 = baseY. scale = 6 기본.
 *   • 표준 골격: torso -19..0(폭 ~12) · neck -21..-19 · head -33..-21(10×12)
 *     · ★ 눈높이 y=-29(형제와 일치) · 코 ~-26 · 입 ~-24.
 *   • 캐릭터 도트만 — 광원/페이드/딤은 호출부 소유. +x 횃불 측 lit / −x shadow.
 *   • R(x,y,w,h,c) fillRect idiom + 함수 상단 로컬 색 토큰(형제 방식).
 *
 * ── v1→v2 교정 (bm 피드백) ───────────────────────────────────────────────────
 *   • "다람쥐"로 읽히던 원인 제거: 높고 뾰족한 귀 + 옆 포니테일 덩어리 →
 *     ▶ 넓고 낮게 **늘어진 개 귀(drop ear)**, 한쪽 끝만 접어 덜렁이 유지.
 *     ▶ 옆 포니테일 볼륨 제거 — 뒤통수 쪽 작은 묶음만(머리 실루엣과 분리).
 *     ▶ 허리 꼬리끝도 북슬 덩어리 → **가늘고 긴 개 꼬리** 끝.
 *   • 무도복·어깨 폴드런 제거 → 초보 모험가/잡일 차림(튜닉+조끼+벨트 파우치).
 *
 * 톤 가드: 고채도 X, 브래스 최대 1점(파우치 클래스프), scale 6 절제.
 */
export function drawQkunPortrait(ctx, cx, baseY, scale = 6) {
    ctx.save();
    ctx.translate(Math.round(cx), Math.round(baseY));
    ctx.scale(scale, scale);
    const R = (x, y, w, h, c) => { ctx.fillStyle = c; ctx.fillRect(x, y, w, h); };

    // ── 색 토큰 (함수 상단; 형제 흉상과 동일 방식의 로컬 팔레트) ──────────
    const SKIN = '#e6b48e', SKIN_SH = '#c48f6c', SKIN_HI = '#f2e4d4';   // 형제와 동일 피부
    const FUR = '#8a5a34', FUR_SH = '#5f3d22', FUR_HI = '#b07d4a';      // 갈색 개 털/머리
    const EAR_IN = '#d99c86';                                          // 귀 안쪽(분홍빛)
    const TUNIC = '#c2a878', TUNIC_SH = '#9a8154', TUNIC_HI = '#dcc79a';// 여행자 튜닉(오트밀 탄)
    const VEST = '#6b4e2e', VEST_SH = '#4c3720', VEST_HI = '#876139';   // 초보 모험가 조끼(갈색)
    const KERCH = '#8b3a1f', KERCH_SH = '#5e2613';                      // rust 네커치프(시그니처 색)
    const POUCH = '#5a4228', POUCH_SH = '#3c2c18';                      // 가죽 벨트/파우치
    const EYE = '#c9883f', EYE_D = '#3a2a1c';                           // 호박색 눈 + 어두운 동공
    const BLUSH = '#d9866a', LIP = '#b56a5e';
    const GOLD = '#e6b450';                                             // 브래스 1점(파우치 클래스프)

    // ════════════════════════════════════════════════════════════════════
    // BUST — 형제와 동일 골격. y 0 = 허리 크롭. 다리/발 없음.
    // ════════════════════════════════════════════════════════════════════

    // ── 꼬리 — 가늘고 긴 개 꼬리. −x 아래 모서리에서 살짝 휘어 올라옴(북슬 X) ─
    R(-8, -4, 2, 4, FUR);                      // 뿌리
    R(-9, -6, 1.5, 3, FUR);                    // 휘어 오름
    R(-9.7, -8, 1.4, 2.5, FUR);
    R(-10.2, -10, 1.2, 2.2, FUR);              // 가늘어지는 끝
    R(-10.2, -10, 0.6, 4, FUR_SH);             // 바깥 그림자
    R(-8.4, -6, 0.6, 3, FUR_HI);               // 안쪽 lit

    // ── TORSO — 여행자 튜닉(오트밀 탄). 어깨 넓고 허리 살짝 tuck. ────────
    R(-7, -19, 14, 9, TUNIC);                  // 어깨+가슴 −19..−10
    R(-6, -10, 12, 10, TUNIC);                 // 허리 −10..0
    R(-7, -19, 2, 9, TUNIC_SH);                // 그림자 측(상)
    R(-6, -10, 2, 10, TUNIC_SH);               // 그림자 측(하)
    R(5, -19, 1, 9, TUNIC_HI);                 // +x lit 모서리(상)
    R(5, -10, 1, 7, TUNIC_HI);                 // +x lit 모서리(하)
    // 가벼운 가슴 볼륨(성인 여성, 절제 — 작은 하이라이트만)
    R(-2.5, -16, 2, 1.4, TUNIC_HI); R(0.7, -16, 2, 1.4, TUNIC_HI);
    R(-2.2, -13.5, 2, 0.7, TUNIC_SH); R(0.7, -13.5, 2, 0.7, TUNIC_SH);

    // ── 초보 모험가 조끼(갈색) — 가슴은 V로 열리고 허리 아래는 닫힘 ───────
    R(-7, -19, 3.5, 19, VEST);                 // 왼 앞판
    R(3.5, -19, 3.5, 19, VEST);                // 오른 앞판
    R(-7, -4, 14, 4, VEST);                    // 아래 닫힘(앞단 — 멜빵 아닌 조끼로 읽히게)
    R(-7, -19, 1.5, 19, VEST_SH);              // 그림자 측 앞판
    R(6, -19, 1, 16, VEST_HI);                 // +x lit 모서리
    R(-3.3, -19, 1.3, 5, VEST_HI);             // 왼 라펠
    R(2, -19, 1.3, 5, VEST_HI);                // 오른 라펠
    R(-3.5, -19, 0.7, 11, VEST_SH);            // V 안쪽 가장자리(좌)
    R(2.8, -19, 0.7, 11, VEST_SH);             // V 안쪽 가장자리(우)
    R(-7, -4, 14, 0.8, VEST_HI);               // 조끼 허리단 하이라이트

    // ── rust 네커치프(시그니처) — 목 아래, 얼굴 곁에 따뜻한 색 ───────────
    R(-3, -19, 6, 1.6, KERCH);                 // 목띠
    R(-3, -19, 1.4, 1.6, KERCH_SH);            // 그림자
    R(-1.3, -17.6, 2.6, 2.6, KERCH);           // 매듭 + 늘어진 끝
    R(-1.3, -17.6, 1, 2.6, KERCH_SH);

    // ── 벨트 + 작은 심부름 파우치(잡일 신입 소품, 1점) ───────────────────
    R(-6, -6.5, 12, 1.6, POUCH);               // 벨트 스트랩
    R(-6, -6.5, 12, 0.5, POUCH_SH);
    R(2.6, -7, 3.4, 4.6, POUCH);               // 파우치 몸체(+x)
    R(2.6, -7, 3.4, 1.3, POUCH_SH);            // 플랩 음영
    R(5.4, -5.8, 0.7, 3, VEST_HI);             // lit 모서리
    R(3.9, -5.4, 1.4, 1, GOLD);                // 클래스프(브래스 1점)
    R(4.1, -5.4, 0.5, 0.5, TUNIC_HI);          // 글린트

    // ── NECK ────────────────────────────────────────────────────────────
    R(-2, -21, 4, 2, SKIN);
    R(-2, -21, 1.5, 2, SKIN_SH);

    // ── HEAD — 둥글고 큰 동안 (형제 골격 −33..−21, 10×12) ────────────────
    R(-5, -33, 10, 12, SKIN);                  // 얼굴
    R(-5, -33, 2, 12, SKIN_SH);                // 그림자 측(−x)
    R(4, -33, 1, 11, SKIN_HI);                 // lit 모서리(+x)
    R(-4, -22, 8, 1, SKIN_SH);                 // 부드러운 턱 음영

    // ── 머리 — 수수한 신입. 이마 프린지 + 짧은 옆머리 + 뒤통수 작은 묶음 ──
    R(-5, -35, 10, 3, FUR);                    // 두상/크라운
    R(-5, -35, 3, 3, FUR_SH);
    R(2, -35, 3, 2, FUR_HI);                   // lit 크라운(+x)
    R(-5, -33, 8, 2, FUR);                     // 이마 프린지
    R(-1, -34, 3, 1, FUR_HI);                  // 가르마 하이라이트
    R(-4.5, -32, 1, 3, FUR);                   // 짧은 옆머리(좌, 귀 안쪽으로)
    R(3.5, -32, 1, 3, FUR);                    // 짧은 옆머리(우)
    // 뒤통수 작은 묶음(머리 실루엣과 분리 — 옆 볼륨 X, 살짝만)
    R(-5.5, -24, 2, 4, FUR);                   // −x 어깨 위 작은 묶음
    R(-5.5, -24, 1, 4, FUR_SH);
    R(-5, -25, 1.5, 1.2, KERCH);               // 작은 rust 머리끈

    // ── 늘어진 개 귀(drop ear) — 머리 위에서 시작해 얼굴 옆으로 넓게 처짐.
    //    "강아지" 신호의 핵심. 한쪽 끝만 접어 덜렁이 유지. ─────────────────
    // 왼 귀(−x, 그림자) — 넓은 flap 이 뺨 옆까지 처짐
    R(-8, -34, 4, 4, FUR);                     // 뿌리(머리 위 측면)
    R(-8.5, -31, 4, 5, FUR);                   // 처지는 몸통(넓게)
    R(-8, -26, 3.5, 4, FUR);                   // 아래 끝(뺨 옆)
    R(-8.5, -33, 1.3, 11, FUR_SH);             // 바깥 그림자 모서리
    R(-4.5, -32, 1, 7, EAR_IN);                // 귀 안쪽(분홍, 얼굴 쪽)
    // 오른 귀(+x, 빛) — 처지다가 끝이 위로 접힘(덜렁이 포인트)
    R(4, -34, 4, 4, FUR);                      // 뿌리
    R(4.5, -31, 4, 4, FUR);                    // 처지는 몸통
    R(6.5, -29, 3, 2.5, FUR);                  // 끝이 바깥-위로 꺾여 접힘
    R(8, -30, 1.2, 2.5, FUR_HI);              // 접힘 lit 모서리
    R(4.5, -32, 1, 6, EAR_IN);                 // 귀 안쪽

    // ── 얼굴 디테일 — 크고 밝은 호박색 눈 + 작은 코 + 활짝 덧니 미소 + 홍조 ─
    //    눈썹은 따로 두지 않음(형제와 동일) — 프린지가 brow 라인 역할.
    R(-3.6, -29, 2.6, 2, '#f6f1e6');           // 왼 흰자
    R(1, -29, 2.6, 2, '#f6f1e6');              // 오른 흰자
    R(-3.2, -29, 1.8, 2, EYE);                 // 왼 홍채(호박)
    R(1.4, -29, 1.8, 2, EYE);                  // 오른 홍채
    R(-2.6, -28.6, 0.9, 1.3, EYE_D);           // 왼 동공
    R(1.8, -28.6, 0.9, 1.3, EYE_D);            // 오른 동공
    R(-3.0, -29, 1.1, 1, SKIN_HI);             // 왼 캐치라이트(반짝)
    R(1.6, -29, 1.1, 1, SKIN_HI);              // 오른 캐치라이트
    R(-1.4, -29, 0.6, 0.6, '#fff');            // 아래 작은 반짝(L)
    R(2.4, -29, 0.6, 0.6, '#fff');             // (R)
    // 작은 코(개 코끝 살짝)
    R(-0.5, -26, 1, 1, FUR_SH);
    // 활짝 웃는 덜렁이 입 — 입꼬리 올라간 열린 미소 + 덧니
    R(-1.8, -24.4, 3.6, 1.4, EYE_D);           // 벌린 입(어둡게)
    R(-2.1, -25, 0.9, 0.9, LIP);               // 왼 입꼬리(살짝 위로)
    R(1.2, -25, 0.9, 0.9, LIP);                // 오른 입꼬리(위로)
    R(-1.2, -23.2, 2.6, 0.7, LIP);             // 아랫입술/혀
    R(-1.4, -24.4, 0.8, 0.8, '#fbf6ea');       // 덧니(fang)
    // 홍조 — 작고 은은하게
    R(-4, -26.2, 1.1, 0.9, BLUSH);
    R(2.9, -26.2, 1.1, 0.9, BLUSH);

    ctx.restore();
}
